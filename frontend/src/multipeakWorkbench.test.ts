import { afterEach, describe, expect, it, vi } from 'vitest';
import { flushPromises, mount } from '@vue/test-utils';
import MultiPeakWorkbench from './components/MultiPeakWorkbench.vue';
import App from './App.vue';
import MultiPeakChart from './components/MultiPeakChart.vue';
import MultiPeakControls from './components/MultiPeakControls.vue';
import Plotly from 'plotly.js-dist-min';
import * as api from './multipeakApi';
import { createMultiConfig } from './multipeakState';
vi.mock('./multipeakApi',()=>({fitMulti:vi.fn(),previewMulti:vi.fn(),candidatesMulti:vi.fn()}));
vi.mock('plotly.js-dist-min',()=>({default:{register:vi.fn(),react:vi.fn((el:any)=>{el.on=vi.fn();el.removeAllListeners=vi.fn();return Promise.resolve();}),purge:vi.fn(),downloadImage:vi.fn()}}));
const wrappers:Array<{unmount:()=>void}>=[];
afterEach(()=>{wrappers.splice(0).forEach(w=>w.unmount());vi.clearAllMocks();});
function workbench(){const w=mount(MultiPeakWorkbench,{props:{x:[0,1,2,3,4],y:[0,1,5,1,0],source:null,mode:'general'}});wrappers.push(w);return w;}
describe('单谱多峰工作区',()=>{
  it('一次开启后连续左键添加，右键删除附近峰，手动取消后停止编辑',async()=>{
    const w=workbench();await w.get('[data-test="multi-baseline"]').setValue('none');
    const plot=w.get('[data-test="multi-plot"]').element as HTMLElement & {_fullLayout:unknown};
    plot._fullLayout={xaxis:{_offset:20,_length:400,range:[0,4]},yaxis:{_offset:50,_length:200}};
    await w.get('[data-test="chart-add-peak"]').trigger('click');
    plot.dispatchEvent(new MouseEvent('pointerdown',{clientX:270,clientY:100,bubbles:true}));
    plot.dispatchEvent(new MouseEvent('pointerup',{clientX:270,clientY:100,bubbles:true}));
    await flushPromises();
    expect((w.get('[aria-label="p1 xc 初值"]').element as HTMLInputElement).value).toBe('2.5');
    expect(w.get('[data-test="chart-add-peak"]').text()).toBe('取消添加峰');
    expect(w.findComponent(MultiPeakChart).emitted('add-peak')?.[0]).toEqual([2.5]);
    const layout=()=>vi.mocked(Plotly.react).mock.calls.filter((call:unknown[])=>call[0]===plot).at(-1)![2] as any;
    expect(layout().annotations).toEqual(expect.arrayContaining([expect.objectContaining({x:2.5,text:expect.stringContaining('p1')})]));
    await w.get('[aria-label="p1 xc 初值"]').setValue(2.8);await flushPromises();
    expect(layout().annotations[0].x).toBe(2.8);
    for(const type of ['pointerdown','pointerup'])plot.dispatchEvent(new MouseEvent(type,{button:0,clientX:370,clientY:100,bubbles:true}));
    await flushPromises();expect(w.find('[aria-label="p2 xc 初值"]').exists()).toBe(true);
    await w.get('[data-test="multi-plot"]').trigger('dblclick');
    expect(w.get('[data-test="chart-add-peak"]').text()).toBe('取消添加峰');
    for(const type of ['pointerdown','pointerup'])plot.dispatchEvent(new MouseEvent(type,{button:2,clientX:300,clientY:100,bubbles:true}));
    await flushPromises();expect(w.find('[aria-label="p1 xc 初值"]').exists()).toBe(false);
    expect(w.find('[aria-label="p2 xc 初值"]').exists()).toBe(true);
    const menu=new MouseEvent('contextmenu',{clientX:300,clientY:100,bubbles:true,cancelable:true});plot.dispatchEvent(menu);expect(menu.defaultPrevented).toBe(true);
    for(const type of ['pointerdown','pointerup'])plot.dispatchEvent(new MouseEvent(type,{button:2,clientX:60,clientY:100,bubbles:true}));
    await flushPromises();expect(layout().annotations).toHaveLength(1);
    await w.get('[data-test="chart-add-peak"]').trigger('click');
    for(const button of [0,2])for(const type of ['pointerdown','pointerup'])plot.dispatchEvent(new MouseEvent(type,{button,clientX:370,clientY:100,bubbles:true}));
    await flushPromises();expect(layout().annotations).toHaveLength(1);
    const normalMenu=new MouseEvent('contextmenu',{bubbles:true,cancelable:true});plot.dispatchEvent(normalMenu);expect(normalMenu.defaultPrevented).toBe(false);
  });
  it('主入口合并通用与 XRD 的单峰和多峰',()=>{const w=mount(App);wrappers.push(w);expect(w.get('[data-test="analysis-mode"]').text()).toContain('通用谱线');expect(w.get('[data-test="analysis-mode"]').text()).toContain('XRD 峰拟合');});
  it('右键删除仍遵守峰间关联保护，右键拖动不删除',async()=>{
    const w=workbench();await w.get('[data-test="multi-add"]').trigger('click');await w.get('[data-test="multi-add"]').trigger('click');
    await w.get('[aria-label="p2 xc 初值"]').setValue(3);
    const config=w.findComponent(MultiPeakControls).props('config');
    config.constraints.push({source:{component:'p1',parameter:'w'},target:{component:'p2',parameter:'w'},kind:'ratio',value:1});
    const plot=w.get('[data-test="multi-plot"]').element as HTMLElement & {_fullLayout:unknown};
    plot._fullLayout={xaxis:{_offset:20,_length:400,range:[0,4]},yaxis:{_offset:50,_length:200}};
    await w.get('[data-test="chart-add-peak"]').trigger('click');
    for(const type of ['pointerdown','pointerup'])plot.dispatchEvent(new MouseEvent(type,{button:2,clientX:220,clientY:100,bubbles:true}));
    await flushPromises();expect(w.get('[role="alert"]').text()).toContain('解除');expect(config.components).toHaveLength(2);
    config.constraints=[];
    for(const [type,x] of [['pointerdown',220],['pointermove',300],['pointerup',220]] as const)plot.dispatchEvent(new MouseEvent(type,{button:2,clientX:x,clientY:100,bubbles:true}));
    await flushPromises();expect(config.components).toHaveLength(2);
  });
  it('拖动返回原点及 Esc 取消都不添加峰',async()=>{
    const w=workbench(),plot=w.get('[data-test="multi-plot"]').element as HTMLElement & {_fullLayout:unknown};
    plot._fullLayout={xaxis:{_offset:20,_length:400,range:[0,4]},yaxis:{_offset:50,_length:200}};
    await w.get('[data-test="chart-add-peak"]').trigger('click');
    for(const [type,x] of [['pointerdown',200],['pointermove',300],['pointerup',200]] as const)plot.dispatchEvent(new MouseEvent(type,{clientX:x,clientY:100,bubbles:true}));
    await flushPromises();expect(w.find('[aria-label="p1 xc 初值"]').exists()).toBe(false);
    await w.findComponent(MultiPeakChart).trigger('keydown',{key:'Escape'});
    expect(w.get('[data-test="chart-add-peak"]').text()).toBe('图上添加峰');
  });
  it('基线预览复核后才允许拟合，区间改变使确认失效',async()=>{
    const w=workbench();await w.get('[data-test="multi-add"]').trigger('click');
    expect((w.get('[data-test="multi-fit"]').element as HTMLButtonElement).disabled).toBe(true);
    expect(w.get('[data-test="multi-fit-blocker"]').text()).toContain('预览基线');
    vi.mocked(api.previewMulti).mockResolvedValue({x:[0,1,2,3,4],raw_y:[0,1,5,1,0],baseline:[0,0,0,0,0],baseline_configuration:{...createMultiConfig([],[],null,'general').baseline,resolved_anchors:[]}});
    await w.get('[data-test="multi-preview-next"]').trigger('click');await flushPromises();
    expect(api.fitMulti).not.toHaveBeenCalled();
    expect((w.get('[data-test="multi-fit"]').element as HTMLButtonElement).disabled).toBe(true);
    expect(w.get('[data-test="multi-fit-blocker"]').text()).toContain('复核');
    await w.get('[data-test="multi-confirm-next"]').trigger('click');
    expect((w.get('[data-test="multi-confirm"]').element as HTMLInputElement).checked).toBe(true);
    expect((w.get('[data-test="multi-fit"]').element as HTMLButtonElement).disabled).toBe(false);
    expect(w.find('[data-test="multi-fit-blocker"]').exists()).toBe(false);
    await w.get('[data-test="multi-range-start"]').setValue(.5);
    expect((w.get('[data-test="multi-confirm"]').element as HTMLInputElement).checked).toBe(false);
    expect(w.find('[data-test="multi-preview-next"]').exists()).toBe(true);
  });
  it('预览失败时保留预览入口，不能跳过复核直接拟合',async()=>{
    const w=workbench();await w.get('[data-test="multi-add"]').trigger('click');
    vi.mocked(api.previewMulti).mockRejectedValueOnce(new Error('基线锚点不足'));
    await w.get('[data-test="multi-preview-next"]').trigger('click');await flushPromises();
    expect(w.get('[role="alert"]').text()).toContain('基线锚点不足');
    expect(w.find('[data-test="multi-confirm-next"]').exists()).toBe(false);
    expect((w.get('[data-test="multi-fit"]').element as HTMLButtonElement).disabled).toBe(true);
    expect((w.get('[data-test="multi-preview-next"]').element as HTMLButtonElement).disabled).toBe(false);
  });
  it('缺少谱线或启用峰时说明原因，无基线时无需复核',async()=>{
    const w=workbench();
    expect(w.get('[data-test="multi-fit-blocker"]').text()).toContain('添加或启用');
    await w.get('[data-test="multi-add"]').trigger('click');
    await w.get('[data-test="multi-baseline"]').setValue('none');
    expect(w.find('[data-test="multi-fit-blocker"]').exists()).toBe(false);
    expect((w.get('[data-test="multi-fit"]').element as HTMLButtonElement).disabled).toBe(false);
    await w.setProps({x:[],y:[]});
    expect(w.get('[data-test="multi-fit-blocker"]').text()).toContain('导入');
  });
  it('编辑参数后丢弃旧请求的返回，不显示旧结果',async()=>{
    const w=workbench();await w.get('[data-test="multi-add"]').trigger('click');await w.get('[data-test="multi-baseline"]').setValue('none');
    let resolve!:(value:any)=>void;vi.mocked(api.fitMulti).mockReturnValue(new Promise(r=>resolve=r));
    await w.get('[data-test="multi-fit"]').trigger('click');
    await w.get('[aria-label="p1 xc 初值"]').setValue(2.3);
    resolve({converged:true});await flushPromises();
    expect(w.text()).toContain('暂无拟合结果');expect(w.find('[data-test="multi-export-curves"]').exists()).toBe(false);
  });
});
