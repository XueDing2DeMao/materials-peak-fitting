import * as protection from './useWorkProtection';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { mount, flushPromises } from '@vue/test-utils';
import MultiPeakWorkbench from './components/MultiPeakWorkbench.vue';
import MultiPeakControls from './components/MultiPeakControls.vue';
import ResultsPanel from './components/ResultsPanel.vue';
import MultiPeakChart from './components/MultiPeakChart.vue';
import * as singleApi from './api';
import * as multiApi from './multipeakApi';
import type { FitResult } from './types';
import { addMultiComponent, createMultiConfig } from './multipeakState';
vi.mock('./api',()=>({runFit:vi.fn(),previewBaseline:vi.fn(),analyzePeak:vi.fn(),compareModels:vi.fn(),downloadExport:vi.fn()}));
vi.mock('./multipeakApi',()=>({fitMulti:vi.fn(),previewMulti:vi.fn(),candidatesMulti:vi.fn()}));
vi.mock('plotly.js-dist-min',()=>({default:{register:vi.fn(),react:vi.fn((el:any)=>{el.on=vi.fn();el.removeAllListeners=vi.fn();return Promise.resolve();}),purge:vi.fn(),downloadImage:vi.fn()}}));
beforeEach(()=>vi.spyOn(protection,'confirmDiscard').mockResolvedValue(true));
const x=[0,1,2,3,4],y=[0,1,5,1,0];
const fitted:FitResult={x,raw_y:y,baseline:x.map(()=>0),net_y:y,peak_y:y,total_y:y,residual:x.map(()=>0),parameters:{A:{value:5,standard_error:null},xc:{value:2,standard_error:null},w:{value:.4,standard_error:null}},statistics:{r_squared:1,adjusted_r_squared:1,rmse:0,sse:0},converged:true,message:'ok',model:'gaussian'};
const wrappers:Array<{unmount:()=>void}>=[];
afterEach(()=>{wrappers.splice(0).forEach(w=>w.unmount());vi.clearAllMocks();vi.restoreAllMocks();});
async function workbench(){const w=mount(MultiPeakWorkbench,{props:{x,y,source:null,mode:'general',unified:true}});wrappers.push(w);await w.get('[data-test="multi-baseline"]').setValue('none');await w.get('[data-test="multi-add"]').trigger('click');return w;}
describe('统一峰拟合工作区',()=>{
  it('参数页签仅改变可见模块，保留输入、基线复核、结果与求解次数',async()=>{
    const w=await workbench();vi.mocked(singleApi.runFit).mockResolvedValue(fitted);
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();
    const config=w.getComponent(MultiPeakControls).props('config'),before=JSON.stringify(config),plot=w.get('[data-test="multi-plot"]').element;
    for(const section of ['baseline','peaks','range'])await w.get(`[data-test="parameter-tab-${section}"]`).trigger('click');
    expect(JSON.stringify(config)).toBe(before);expect(singleApi.runFit).toHaveBeenCalledTimes(1);
    expect(singleApi.previewBaseline).not.toHaveBeenCalled();expect(w.get('[data-test="multi-plot"]').element).toBe(plot);
    expect(w.getComponent(ResultsPanel).props('stale')).toBe(false);
    await w.get('[data-test="parameter-tab-range"]').trigger('keydown',{key:'ArrowRight'});
    expect(w.get('[data-test="parameter-tab-baseline"]').attributes('aria-selected')).toBe('true');
  });
  it('结果定位使用稳定峰 ID，不把优化参数覆盖编辑初值',async()=>{
    const w=await workbench();vi.mocked(singleApi.runFit).mockResolvedValue({...fitted,parameters:{...fitted.parameters,xc:{value:2.1,standard_error:null}}});
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();
    const config=w.getComponent(MultiPeakControls).props('config'),before=JSON.stringify(config);
    await w.get('[data-test="locate-peak-p1"]').trigger('click');await flushPromises();
    expect(w.get('[data-test="parameter-tab-peaks"]').attributes('aria-selected')).toBe('true');
    expect(w.getComponent(MultiPeakChart).props('selectedPeak')).toBe('p1');expect(JSON.stringify(config)).toBe(before);
    await w.get('[data-test="result-view-parameters"]').trigger('click');
    expect(w.find('[data-test="peak-overview"]').exists()).toBe(true);expect(singleApi.runFit).toHaveBeenCalledTimes(1);
  });

  it('紧凑锚点编辑保留坐标对应关系，编辑和删除均撤销复核',async()=>{
    const w=await workbench(),config=w.getComponent(MultiPeakControls).props('config');
    await w.get('[data-test="multi-baseline"]').setValue('line');
    config.baseline.anchors=[{x:0,y:1},{x:2,y:3},{x:4,y:1}];await flushPromises();
    config.baseline.confirmed=true;await flushPromises();
    await w.get('[aria-label="锚点 2 Y"]').setValue(2.5);await flushPromises();
    expect(config.baseline.anchors).toEqual([{x:0,y:1},{x:2,y:2.5},{x:4,y:1}]);
    expect(config.baseline.confirmed).toBe(false);
    config.baseline.confirmed=true;await flushPromises();
    await w.get('[aria-label="删除锚点 2"]').trigger('click');await flushPromises();
    expect(config.baseline.anchors).toEqual([{x:0,y:1},{x:4,y:1}]);
    expect((w.get('[aria-label="锚点 2 X"]').element as HTMLInputElement).value).toBe('4');
    expect(config.baseline.confirmed).toBe(false);
    config.baseline.confirmed=true;await flushPromises();
    w.getComponent(MultiPeakChart).vm.$emit('move-anchor',0,{x:.5,y:1.5});await flushPromises();
    expect(config.baseline.anchors[0]).toEqual({x:.5,y:1.5});expect(config.baseline.confirmed).toBe(false);
    expect(singleApi.runFit).not.toHaveBeenCalled();expect(multiApi.fitMulti).not.toHaveBeenCalled();
  });
  it('切换结果视图保留模型比较选项和拟合结果，不重新求解',async()=>{
    const w=await workbench();vi.mocked(singleApi.runFit).mockResolvedValue(fitted);
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();
    const plot=w.get('[data-test="multi-plot"]').element;
    await w.get('[data-test="result-view-archive"]').trigger('click');
    await w.get('[data-test="include-asymmetric"]').setValue(true);
    await w.get('[data-test="result-view-diagnostics"]').trigger('click');
    await w.get('[data-test="result-view-results"]').trigger('click');
    await w.get('[data-test="result-view-archive"]').trigger('click');
    expect((w.get('[data-test="include-asymmetric"]').element as HTMLInputElement).checked).toBe(true);
    expect(w.get('[data-test="multi-plot"]').element).toBe(plot);
    expect(w.getComponent(ResultsPanel).props('result')).toEqual(fitted);
    expect(singleApi.runFit).toHaveBeenCalledTimes(1);
  });
  it('导入、更换数据和切换模式均不自动建峰或检测候选峰',async()=>{
    const w=mount(MultiPeakWorkbench,{props:{x,y,source:null,mode:'general',unified:true}});wrappers.push(w);
    const config=()=>w.getComponent(MultiPeakControls).props('config');
    expect(config().components).toHaveLength(0);
    expect(w.get('[data-test="multi-fit"]').attributes('disabled')).toBeDefined();
    await w.get('[data-test="multi-range-start"]').setValue(.5);
    expect(config().components).toHaveLength(0);
    await w.get('[data-test="multi-add"]').trigger('click');
    expect(config().components).toHaveLength(1);
    await w.setProps({y:[0,2,6,2,0]});expect(config().components).toHaveLength(0);
    await w.setProps({mode:'xrd'});expect(config().components).toHaveLength(0);
    expect(multiApi.candidatesMulti).not.toHaveBeenCalled();expect(singleApi.analyzePeak).not.toHaveBeenCalled();
  });
  it('统一峰函数应用到所有峰，按钮、图选及删空后新增都沿用选择',async()=>{
    const w=await workbench(),config=w.getComponent(MultiPeakControls).props('config');
    await w.get('[data-test="multi-add"]').trigger('click');
    config.components[1].enabled=false;
    await w.get('[data-test="multi-model"]').setValue('psd_voigt2');
    expect(config.components.map(c=>c.model)).toEqual(['psd_voigt2','psd_voigt2']);
    w.getComponent(MultiPeakChart).vm.$emit('add-peak',2.5);await flushPromises();
    expect(config.components[2].model).toBe('psd_voigt2');expect(config.components[2].parameters.wG).toBeDefined();
    for(const id of ['p1','p2','p3'])w.getComponent(MultiPeakChart).vm.$emit('remove-peak',id);
    await flushPromises();await w.get('[data-test="multi-add"]').trigger('click');
    expect(config.components[0].model).toBe('psd_voigt2');
  });
  it('旧混合峰配置原样恢复，显式统一后才可拟合',async()=>{
    const source={filename:'mixed.csv',file_sha256:'abc',sheet:'data',x_column:'x',y_column:'y'};
    const config=createMultiConfig(x,y,source,'general');config.baseline.kind='none';
    addMultiComponent(config,undefined,null,'gaussian');addMultiComponent(config,undefined,null,'lorentz');
    vi.mocked(multiApi.previewMulti).mockResolvedValue({x,raw_y:y,baseline:x.map(()=>0),baseline_configuration:{...config.baseline,resolved_anchors:[]}});
    const w=mount(MultiPeakWorkbench,{props:{x,y,source,mode:'general',unified:true}});wrappers.push(w);
    const file=new File([],'mixed.json');Object.defineProperty(file,'text',{value:async()=>JSON.stringify({configuration:config})});
    const input=w.get('input[type=file]');Object.defineProperty(input.element,'files',{value:[file]});
    const original=w.getComponent(MultiPeakControls).props('config');original.range_start=.25;
    vi.mocked(protection.confirmDiscard).mockResolvedValueOnce(false);
    await input.trigger('change');await flushPromises();
    expect(protection.confirmDiscard).toHaveBeenLastCalledWith(true,expect.any(String));
    expect(w.getComponent(MultiPeakControls).props('config')).toBe(original);
    await input.trigger('change');await flushPromises();
    const restored=w.getComponent(MultiPeakControls).props('config');
    expect(restored.components.map(c=>c.model)).toEqual(['gaussian','lorentz']);
    expect(w.get('[data-test="multi-fit-blocker"]').text()).toContain('统一峰函数');
    await w.get('[data-test="all-peaks-model"]').setValue('psd_voigt1');
    expect(restored.components.every(c=>c.model==='psd_voigt1')).toBe(true);
    expect(w.get('[data-test="multi-fit"]').attributes('disabled')).toBeUndefined();
    vi.mocked(multiApi.fitMulti).mockRejectedValueOnce(new Error('test response'));
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();
    expect(multiApi.fitMulti).toHaveBeenCalledWith(expect.objectContaining({components:expect.arrayContaining([expect.objectContaining({id:'p1',model:'psd_voigt1'}),expect.objectContaining({id:'p2',model:'psd_voigt1'})])}));
  });
  it('原单峰允许的收敛阈值可以预览并恢复自己的配置',async()=>{
    const source={filename:'test.csv',file_sha256:'abc',sheet:'data',x_column:'x',y_column:'y'};
    const w=mount(MultiPeakWorkbench,{props:{x,y,source,mode:'general',unified:true}});wrappers.push(w);
    await w.get('[data-test="multi-add"]').trigger('click');
    const config=w.getComponent(MultiPeakControls).props('config');config.solver.tolerance=.01;
    vi.mocked(singleApi.previewBaseline).mockResolvedValue({x,baseline:x.map(()=>0)});
    await w.get('[data-test="multi-preview"]').trigger('click');await flushPromises();
    expect(singleApi.previewBaseline).toHaveBeenCalledWith(expect.objectContaining({tolerance:.01}));
    expect(multiApi.previewMulti).not.toHaveBeenCalled();
    const artifact={configuration:config,single_solver_settings:{staged:false,centerEvaluations:35}};
    const file=new File([],'one.json');Object.defineProperty(file,'text',{value:async()=>JSON.stringify(artifact)});
    const input=w.get('input[type=file]');Object.defineProperty(input.element,'files',{value:[file]});
    await input.trigger('change');await flushPromises();
    expect(w.find('[role=alert]').exists()).toBe(false);
    expect(singleApi.previewBaseline).toHaveBeenLastCalledWith(expect.objectContaining({tolerance:.01,staged_fit:false,center_lock_evaluations:35}));
    expect(w.getComponent(MultiPeakControls).props('config').baseline.confirmed).toBe(false);
  });
  it('手动添加一个峰走原单峰求解，增删峰保留参数并自动选择联合求解',async()=>{
    const w=await workbench(),config=w.getComponent(MultiPeakControls).props('config');
    expect(config.components).toHaveLength(1);
    await w.get('[aria-label="p1 xc 初值"]').setValue(2.1);
    await w.get('[aria-label="p1 xc 下限"]').setValue(1.8);
    await w.get('[aria-label="p1 xc 固定"]').setValue(true);
    vi.mocked(singleApi.runFit).mockResolvedValue(fitted);
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();
    expect(singleApi.runFit).toHaveBeenCalledWith(expect.objectContaining({model:'gaussian',initial_parameters:expect.objectContaining({xc:2.1}),fixed_parameters:{xc:2.1},parameter_bounds:{xc:{lower:1.8}},staged_fit:true}));
    await w.get('[data-test="multi-add"]').trigger('click');
    expect(config.components).toHaveLength(2);expect(config.components[0].parameters.xc!.value).toBe(2.1);
    vi.mocked(multiApi.fitMulti).mockRejectedValue(new Error('test response'));
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();expect(multiApi.fitMulti).toHaveBeenCalledTimes(1);
    await w.get('[aria-label="启用 p2"]').setValue(false);
    await w.get('[data-test="multi-fit"]').trigger('click');await flushPromises();expect(singleApi.runFit).toHaveBeenCalledTimes(2);
    expect(config.components).toHaveLength(2);
  });
  it('添加峰会使尚未完成的单峰响应失效',async()=>{
    const w=await workbench();let finish!:(r:FitResult)=>void;
    vi.mocked(singleApi.runFit).mockReturnValue(new Promise(resolve=>finish=resolve));
    await w.get('[data-test="multi-fit"]').trigger('click');
    await w.get('[data-test="multi-add"]').trigger('click');finish(fitted);await flushPromises();
    expect(w.text()).not.toContain('ok');expect(w.findComponent(ResultsPanel).exists()).toBe(false);
  });
  it('单峰初值估计保留固定与边界，生成与图选锚点都会撤销基线确认',async()=>{
    const w=await workbench(),config=w.getComponent(MultiPeakControls).props('config'),p=config.components[0];
    p.parameters.xc!.fixed=true;p.parameters.A!.upper=3;
    vi.mocked(singleApi.analyzePeak).mockResolvedValue({model:'gaussian',initial_parameters:{xc:1,A:8,w:.5},candidate_count:1,selected_index:0,prominence:5,smoothing_window:3,method:'test'});
    await w.get('[data-test="auto-analyze"]').trigger('click');await flushPromises();
    expect(p.parameters.xc!.value).toBe(2);expect(p.parameters.A!.value).toBe(3);
    await w.get('[data-test="multi-baseline"]').setValue('polynomial');
    const suggestion=w.findAll('button').find(b=>b.text()==='生成建议锚点')!;await suggestion.trigger('click');
    expect(config.baseline.anchors.length).toBeGreaterThanOrEqual(3);
    config.baseline.confirmed=true;
    w.getComponent(MultiPeakChart).vm.$emit('anchor',{x:1.5,y:1});await flushPromises();
    expect(config.baseline.anchors.at(-1)).toEqual({x:1.5,y:1});expect(config.baseline.confirmed).toBe(false);
  });
});
